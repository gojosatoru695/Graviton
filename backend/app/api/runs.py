"""
FastAPI Router for Jarvis LangGraph Agent Runs.
Manages run creation, status inspection, human-in-the-loop approvals, and rejections.
"""

import os
import uuid
from typing import Any, Dict, List, Optional
from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel, Field

from app.runtime.checkpointer import DatabaseCheckpointer
from app.runtime.graph import resume_agent_workflow, run_agent_workflow
from app.runtime.state import JarvisState

router = APIRouter(prefix="/runs", tags=["Agent Runs"])
checkpointer = DatabaseCheckpointer()


# -----------------------------------------------------------------------------
# Schemas
# -----------------------------------------------------------------------------
class RunResponse(BaseModel):
    """
    Standardized, clean execution response required by the specification.
    """
    run_id: str = Field(..., description="Unique run identifier.")
    case_id: Optional[str] = Field(None, description="Primary case identifier generated by the run.")
    status: str = Field(..., description="Lifecycle status ('waiting_approval', 'completed', 'rejected', 'failed').")
    output_summary: Optional[str] = Field(None, description="Human-readable operational finding summary.")
    approval_id: Optional[str] = Field(None, description="Identifier of the staged approval request if waiting.")


class StartRunRequest(BaseModel):
    """
    Payload for initiating a new agent workflow run.
    """
    files: Optional[Dict[str, str]] = Field(
        None,
        description="Dictionary mapping filename to raw CSV/text content. If omitted, loads from default demo data directory.",
    )
    customer_name: Optional[str] = Field(None, description="Target customer context.")
    current_date: Optional[str] = Field("2024-10-14", description="Base reference date (YYYY-MM-DD).")


class ApprovalDecisionRequest(BaseModel):
    """
    Seller decision payload to resolve a staged approval.
    """
    decision: str = Field(..., description="'APPROVED' or 'REJECTED'")
    rejection_reason: Optional[str] = Field(None, description="Required explanation if decision is REJECTED.")


def _load_default_demo_files() -> Dict[str, str]:
    """Loads files from data/ directory if no raw payload is provided."""
    data_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "data"))
    file_map: Dict[str, str] = {}
    for filename in ["orders.csv", "invoices.csv", "bank_statement.csv", "settlement_report.csv", "whatsapp_export.txt"]:
        fpath = os.path.join(data_dir, filename)
        if os.path.exists(fpath):
            with open(fpath, "r", encoding="utf-8-sig") as f:
                file_map[filename] = f.read()
    return file_map


# -----------------------------------------------------------------------------
# Endpoints
# -----------------------------------------------------------------------------
@router.post("", response_model=RunResponse)
def start_run(request: StartRunRequest):
    """
    Launches a new LangGraph agent workflow run.
    Executes through normalization, promise extraction, reconciliation, case building,
    and pauses cleanly at 'waiting_approval' when human action is staged.
    """
    run_id = f"run_{uuid.uuid4().hex[:8]}"
    raw_files = request.files or _load_default_demo_files()

    initial_state: JarvisState = {
        "run_id": run_id,
        "correlation_id": run_id,
        "status": "running",
        "current_node": "START",
        "raw_files": raw_files,
        "customer_name": request.customer_name,
        "current_date": request.current_date or "2024-10-14",
        "orders": [],
        "invoices": [],
        "bank_transactions": [],
        "settlement_data": None,
        "promises": [],
        "reconciliation_matches": [],
        "unmatched_items": [],
        "duplicate_groups": [],
        "findings": [],
        "transition_logs": [],
    }

    final_state = run_agent_workflow(initial_state)

    return RunResponse(
        run_id=final_state["run_id"],
        case_id=final_state.get("case_id"),
        status=final_state.get("status", "completed"),
        output_summary=final_state.get("output_summary"),
        approval_id=final_state.get("approval_id"),
    )


@router.get("", response_model=List[Dict[str, Any]])
def list_runs():
    """
    Returns all historical runs and their checkpoint statuses.
    """
    return checkpointer.list_all_runs()


@router.get("/{run_id}", response_model=Dict[str, Any])
def get_run(run_id: str):
    """
    Retrieves detailed execution state, checkpoint, and transition history for a run.
    """
    state = checkpointer.load_checkpoint(run_id)
    if not state:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found.")

    return {
        "run_id": state.get("run_id"),
        "case_id": state.get("case_id"),
        "status": state.get("status"),
        "current_node": state.get("current_node"),
        "output_summary": state.get("output_summary"),
        "approval_id": state.get("approval_id"),
        "action_proposal": state.get("action_proposal"),
        "execution_result": state.get("execution_result"),
        "receipt": state.get("receipt"),
        "transition_logs": state.get("transition_logs", []),
    }


@router.post("/{run_id}/approve", response_model=RunResponse)
def approve_run(run_id: str):
    """
    Approves the pending action, resuming workflow from 'execute_approved_action' to 'generate_receipt'.
    """
    existing = checkpointer.load_checkpoint(run_id)
    if not existing:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found.")

    resumed_state = resume_agent_workflow(run_id, decision="APPROVED")
    if not resumed_state:
        raise HTTPException(status_code=500, detail="Failed to resume workflow run.")

    return RunResponse(
        run_id=resumed_state["run_id"],
        case_id=resumed_state.get("case_id"),
        status=resumed_state.get("status", "completed"),
        output_summary=resumed_state.get("output_summary"),
        approval_id=resumed_state.get("approval_id"),
    )


@router.post("/{run_id}/reject", response_model=RunResponse)
def reject_run(run_id: str, payload: Optional[ApprovalDecisionRequest] = None):
    """
    Rejects the pending action, triggering rejection cleanup and creating an immutable rejection receipt.
    """
    existing = checkpointer.load_checkpoint(run_id)
    if not existing:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found.")

    reason = payload.rejection_reason if payload else "Rejected by seller."
    resumed_state = resume_agent_workflow(run_id, decision="REJECTED", rejection_reason=reason)
    if not resumed_state:
        raise HTTPException(status_code=500, detail="Failed to resume workflow run.")

    return RunResponse(
        run_id=resumed_state["run_id"],
        case_id=resumed_state.get("case_id"),
        status=resumed_state.get("status", "rejected"),
        output_summary=resumed_state.get("output_summary"),
        approval_id=resumed_state.get("approval_id"),
    )
